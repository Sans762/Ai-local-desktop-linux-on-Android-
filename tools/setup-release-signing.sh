#!/usr/bin/env bash
# One-time owner setup. Run from an authenticated GitHub Codespace or computer.
# Never checks a release key into this public repository.
set -euo pipefail
umask 077

REPO="Sans762/Ai-local-desktop-linux-on-Android-"
KEY_HOME="${HOME}/.local/share/localai-release-signing"
KEYSTORE="${KEY_HOME}/localai-release.p12"
CREDENTIALS="${KEY_HOME}/signing-credentials.env"
KEY_ALIAS="localai-release"

for cmd in gh keytool openssl base64; do
  if ! command -v "$cmd" >/dev/null; then
    echo "Missing $cmd. Install the command before running setup."
    exit 1
  fi
done
if ! gh auth status >/dev/null 2>&1; then
  echo "Sign in to GitHub first: gh auth login --web --scopes repo,workflow"
  exit 1
fi
mkdir -p "$KEY_HOME"

if [[ -f "$KEYSTORE" && ! -f "$CREDENTIALS" || ! -f "$KEYSTORE" && -f "$CREDENTIALS" ]]; then
  echo "Partial signing setup detected. Do not create another key or future APK updates will fail."
  echo "Restore the missing file from your secure backup: $KEY_HOME"
  exit 1
fi

if [[ ! -f "$KEYSTORE" ]]; then
  PASSWORD="$(openssl rand -hex 32)"
  # A PKCS12 keystore uses the same high-entropy password for the store and key.
  keytool -genkeypair -noprompt \
    -alias "$KEY_ALIAS" -keyalg RSA -keysize 4096 -validity 10000 \
    -storetype PKCS12 -keystore "$KEYSTORE" \
    -storepass "$PASSWORD" -keypass "$PASSWORD" \
    -dname "CN=Local AI Linux Desktop, O=Personal, C=TH" >/dev/null 2>&1
  chmod 600 "$KEYSTORE"
  printf "RELEASE_KEY_ALIAS=%s\nRELEASE_KEYSTORE_PASSWORD=%s\nRELEASE_KEY_PASSWORD=%s\n" \
    "$KEY_ALIAS" "$PASSWORD" "$PASSWORD" > "$CREDENTIALS"
  chmod 600 "$CREDENTIALS"
  unset PASSWORD
  echo "A permanent signing key was created in your private Codespace."
else
  echo "Using the SAME existing signing key. No new key was created."
fi

# The credentials file was generated by this script and is never part of git.
source "$CREDENTIALS"
base64 < "$KEYSTORE" | tr -d '\n' | gh secret set RELEASE_KEYSTORE_BASE64 -R "$REPO"
printf "%s" "$RELEASE_KEYSTORE_PASSWORD" | gh secret set RELEASE_KEYSTORE_PASSWORD -R "$REPO"
printf "%s" "$RELEASE_KEY_ALIAS" | gh secret set RELEASE_KEY_ALIAS -R "$REPO"
printf "%s" "$RELEASE_KEY_PASSWORD" | gh secret set RELEASE_KEY_PASSWORD -R "$REPO"

echo ""
echo "Release signing secrets registered in GitHub Actions."
echo "!!! IMPORTANT: Make an OFFLINE SECURE BACKUP of BOTH files before"
echo "!!! deleting this Codespace:"
echo "    $KEYSTORE"
echo "    $CREDENTIALS"
echo "Do not paste these files or password into chat or a public repository."
echo "Losing this signing key means future in-place Android updates are IMPOSSIBLE."
echo ""
echo "Checking that GitHub accepts workflow dispatch..."
gh workflow run build-apk.yml -R "$REPO"
echo "A signed APK build was requested. It will publish in GitHub Releases once CI succeeds."
